"""Сортировка Помещений внутри Здания.

Прилегающие парковки (parking_type='adjacent') всегда идут первыми (у них нет
этажа — они снаружи здания), между собой по названию. Далее — остальные
помещения: числовая часть этажа по убыванию (верхние этажи выше), затем
буквенная часть этажа А→Я, затем название А→Я. Помещения без числового
этажа уходят в конец списка. Этаж — строка вида «5», «1А», «-1P»,
«-1 Паркинг»; всегда начинается с (возможно отрицательной) цифры.
"""
import re

_FLOOR_RE = re.compile(r"^(-?\d+)(.*)$")


def room_sort_key(room):
    name = (room.name or "").lower()
    # Прилегающие парковки — всегда выше остальных помещений.
    if room.parking_type == "adjacent":
        return (0, 0, "", name)
    floor = (room.floor or "").strip()
    m = _FLOOR_RE.match(floor)
    if m:
        return (1, -int(m.group(1)), m.group(2).strip().lower(), name)
    # Без числового этажа — в конец, между собой по названию.
    return (2, 0, floor.lower(), name)
