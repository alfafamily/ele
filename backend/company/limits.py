"""Настраиваемый лимит размера загружаемого файла (Настройки → Системные →
Хранилище приложения). Единый источник для валидации во всех разделах, где
грузятся файлы-реквизиты и планы помещений. Аватары/лого имеют собственный
фиксированный лимит и сюда не относятся."""


def max_upload_mb() -> int:
    from .models import Company

    return Company.load().max_upload_mb


def max_upload_bytes() -> int:
    return max_upload_mb() * 1024 * 1024
